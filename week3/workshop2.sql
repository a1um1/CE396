CREATE TABLE IF NOT EXISTS "Profile" (
	"id" SERIAL NOT NULL,
	"name" VARCHAR(60) NOT NULL,
	"citizenID" VARCHAR(13) NOT NULL,
	"address" VARCHAR(255) NOT NULL,
	"amphoe" VARCHAR(255) NOT NULL,
	"tambon" VARCHAR(255) NOT NULL,
	"province" VARCHAR(255) NOT NULL,
	"postalcode" VARCHAR(255) NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "PhoneNumbers" (
	"id" SERIAL NOT NULL,
	"ProfileID" INTEGER NOT NULL,
	"PhoneNumber" VARCHAR(11) NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "Client" (
	"Id" SERIAL NOT NULL,
	"profileID" SERIAL NOT NULL UNIQUE,
	PRIMARY KEY("Id")
);

CREATE TABLE IF NOT EXISTS "Animal" (
	"id" SERIAL NOT NULL,
	"OwnerID" INTEGER NOT NULL,
	"name" VARCHAR(255),
	"type" VARCHAR(255) NOT NULL,
	"birthday" DATE NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "Doctor" (
	"id" SERIAL NOT NULL,
	"profileID" INTEGER NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "DoctorToAbility" (
	"id" SERIAL NOT NULL,
	"DoctorID" INTEGER NOT NULL,
	"AbilityID" INTEGER NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "Ability" (
	"id" SERIAL NOT NULL,
	"Name" VARCHAR(255) NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "MedicalRecord" (
	"id" SERIAL NOT NULL,
	"AnimalID" INTEGER NOT NULL,
	"DoctorID" INTEGER NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "Recipt" (
	"id" SERIAL NOT NULL,
	"MedicalRecordID" INTEGER NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "MedicalToMedecine" (
	"id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"MedicalID" INTEGER NOT NULL,
	"MedicineRecord" INTEGER NOT NULL,
	PRIMARY KEY("id")
);

CREATE TABLE IF NOT EXISTS "MedecineRecord" (
	"id" SERIAL NOT NULL,
	"name" VARCHAR(255) NOT NULL,
	"pricePerUnit" NUMERIC NOT NULL,
	"amountGiven" INTEGER NOT NULL,
	"size" VARCHAR(255) NOT NULL,
	"givenAt" DATE NOT NULL,
	"lastFor" INTEGER NOT NULL,
	PRIMARY KEY("id")
);

